import type { Case } from "./CaseHeader";

/** Общее для форм рождений, браков и смертей — что им сообщает окно. */
export type FormProps = {
  mkCase: Case;
  /** Запись сохранена — дело, к которому она привязана. */
  onSaved: (caseId: number) => void;
  /** Экран «Дело» сохранён с этим годом: форма встаёт на него. */
  workYear: { year: number; n: number; fresh?: boolean;
              /** Разделы, где у года нет записей (1 — рождения, 2 — браки, 3 — смерти). */
              freshSections?: number[];
              /** Форма, где сменили год: только она идёт за ним (Роман 24.11.2026). */
              section: 1 | 2 | 3 } | null;
  /** «Открыть запись» из списка на сверку: раздел и номер записи. */
  openReq: { section: number; id: number; n: number } | null;
  /** Год на форме сменили: если в нём ещё нет записей, форма встаёт на него с
   *  чистого листа (Роман 19.10.2026); другие формы не трогаются (Роман
   *  24.11.2026). Ответ — новый ли это год. */
  onNewYear?: (year: number, from: number | null) => Promise<boolean>;
  /** Год новой записи на форме (1 — рождения, 2 — браки, 3 — смерти): скан
   *  вкладки — папка и лист этого года (Роман 24.11.2026: смерти 1904 и
   *  рождения 1905 — у каждой свой скан). Запись на правке его не меняет. */
  onYear?: (section: 1 | 2 | 3, year: number) => void;
};
